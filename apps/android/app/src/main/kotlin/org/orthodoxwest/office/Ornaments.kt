/**
 * The vault tile's edge for a field `width` wide (`--apse-tile`): the stars spread as the screen
 * widens, so a painted ceiling never reads as a wallpaper of small stars. The fields span the
 * screen, so their width is the web's viewport.
 */
private fun vaultTile(width: Dp): Dp = when {
    width >= 2400.dp -> 960.dp
    width >= 1800.dp -> 832.dp
    width >= WideFrom -> 704.dp
    else -> 528.dp
}

/** Tiles `w`×`h` across this scope from its centre, and down it from `seam`. */
private fun DrawScope.tiles(w: Float, h: Float, seam: Float, draw: DrawScope.() -> Unit) {
    val x0 = (size.width / 2f - w / 2f).mod(w) - w
    var y = seam.mod(h)
    if (y > 0f) y -= h
    while (y < size.height) {
        var x = x0
        while (x < size.width) {
            // Each tile clipped to itself, as a repeating mask is, so a shape across its edge is
            // painted once, not by both tiles.
            translate(x, y) { clipRect(0f, 0f, w, h) { draw() } }
            x += w
        }
        y += h
    }
}

/**
 * The field a page's wall carries (apse-vault.md), home's and the hour's ending: by night the
 * Apse vault, the hand-set stars of one tile each at its own opacity in the gilding; by day the
 * Nave's powdering, one rosette to each cell of a quincunx in the rubrics' red at 12%, its tile
 * (96×168) never scaled. Tiled from the field's centre and from `seam` down it, and faded by
 * `fade`'s stops of (fraction, alpha), for the field's size in either theme.
 */
@Composable
fun WallField(modifier: Modifier, seam: Dp = 0.dp, fade: DrawScope.(dark: Boolean) -> List<Pair<Float, Float>>) {
    val p = LocalPalette.current
    val star = LocalOrnament.current.flat
    val rosette = p.rubric.copy(alpha = 0.12f)
    Canvas(modifier.graphicsLayer { compositingStrategy = CompositingStrategy.Offscreen }) {
        if (p.dark) {
            val tile = vaultTile(size.width.toDp()).toPx()
            val k = tile / 528f
            tiles(tile, tile, seam.toPx()) {
                scale(k, k, pivot = Offset.Zero) { for ((alpha, s) in VaultStars) drawPath(s, star, alpha = alpha) }
            }
        } else {
            val k = 96.dp.toPx() / 96f
            tiles(96.dp.toPx(), 168.dp.toPx(), seam.toPx()) {
                scale(k, k, pivot = Offset.Zero) { drawPath(Powder, rosette) }
            }
        }
        val stops = fade(p.dark)
        drawRect(Brush.verticalGradient(*stops.map { (at, a) -> at to Color.Black.copy(alpha = a) }.toTypedArray()), blendMode = BlendMode.DstIn)
    }
}

